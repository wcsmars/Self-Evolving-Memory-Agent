class Store:
    def __init__(self, root: str | Path):
        self.root = Path(root).expanduser().resolve()
        self.root.mkdir(mode=0o700, parents=True, exist_ok=True)
        self.db_path = self.root / "index.sqlite3"
        self._lock = threading.RLock()
        self.projection_errors = []
        for name in ("memory", "evidence"):
            path = self.root / name
            if path.is_symlink():
                raise ValueError(f"Managed directory {name} cannot be a symbolic link")
            path.mkdir(mode=0o700, exist_ok=True)
        if self.db_path.is_symlink():
            raise ValueError("Database cannot be a symbolic link")
        with contextlib.closing(self.connection()) as conn:
            conn.execute("PRAGMA journal_mode=WAL")
            conn.executescript(_SCHEMA)
            conn.commit()
        try:
            self.db_path.chmod(0o600)
        except OSError:
            pass

    def connection(self) -> sqlite3.Connection:
        """Open a connection; the caller must close it (``with`` only commits)."""
        conn = sqlite3.connect(str(self.db_path), timeout=15)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys=ON")
        conn.execute("PRAGMA busy_timeout=15000")
        return conn

    @staticmethod
    def _event(conn, event_type: str, data: dict):
        conn.execute(
            "INSERT INTO events(event_type,created_at,data) VALUES (?,?,?)",
            (event_type, utcnow(), json.dumps(data, ensure_ascii=False, allow_nan=False)),
        )

    def add_memory(self, content: str, kind: str = "note", topic: str = "inbox",
                   subject=None, predicate=None, value=None, valid_from=None,
                   valid_until=None, confidence: float = .8, importance: float = .5,
                   source: str = "manual", source_text=None) -> dict:
        return self.add_memories([{
            "content": content, "kind": kind, "topic": topic,
            "subject": subject, "predicate": predicate, "value": value,
            "valid_from": valid_from, "valid_until": valid_until,
            "confidence": confidence, "importance": importance,
            "source": source, "source_text": source_text,
        }])[0]

    @staticmethod
    def _prepare_add(item: dict) -> tuple:
        defaults = {
            "kind": "note", "topic": "inbox", "subject": None, "predicate": None,
            "value": None, "valid_from": None, "valid_until": None,
            "confidence": .8, "importance": .5, "source": "manual", "source_text": None,
        }
        if not isinstance(item, dict) or "content" not in item:
            raise ValueError("Each memory must be an object with content")
        if not item.keys() <= set(defaults) | {"content"}:
            raise ValueError("Memory contains unsupported fields")
        item = {**defaults, **item}
        now = utcnow()
        source = _text(item["source"], "source", 1_000)
        evidence = item["content"] if item["source_text"] is None else item["source_text"]
        _text(evidence, "source_text", 1_000_000)
        source_id = "s_" + uuid.uuid4().hex
        row = _validate_memory({
            "id": "m_" + uuid.uuid4().hex, "content": item["content"], "kind": item["kind"],
            "topic": item["topic"], "subject": item["subject"], "predicate": item["predicate"], "value": item["value"],
            "valid_from": normalize_time(item["valid_from"]), "valid_until": item["valid_until"],
            "status": "active", "confidence": item["confidence"], "importance": item["importance"],
            "version": 1, "created_at": now, "updated_at": now, "source_id": source_id,
        })
        return row, {"id": source_id, "text": evidence, "label": source, "created_at": now}

    def add_memories(self, items: list[dict]) -> list[dict]:
        """Validate an ingestion batch first, then save all records atomically."""
        if not isinstance(items, list) or len(items) > 10_000:
            raise ValueError("items must be a list with at most 10000 memories")
        prepared = [self._prepare_add(item) for item in items]
        if not prepared:
            return []
        shared = {}
        for row, source in prepared:
            first = shared.setdefault((source["label"], source["text"]), source)
            row["source_id"] = first["id"]
        with self._lock, contextlib.closing(self.connection()) as conn:
            try:
                conn.execute("BEGIN IMMEDIATE")
                for source in shared.values():
                    conn.execute("INSERT INTO sources(id,text,label,created_at) VALUES (?,?,?,?)",
                                 tuple(source[key] for key in ("id", "text", "label", "created_at")))
                for row, _ in prepared:
                    columns = tuple(row)
                    conn.execute(
                        f"INSERT INTO memories ({','.join(columns)}) VALUES ({','.join('?' for _ in columns)})",
                        tuple(row[c] for c in columns),
                    )
                    self._event(conn, "memory_added", {"memory_id": row["id"], "after": row})
                conn.commit()
            except Exception:
                conn.rollback()
                raise
        self.refresh_projections()
        return [row for row, _ in prepared]

    def get_memory(self, memory_id: str) -> dict:
        with contextlib.closing(self.connection()) as conn:
            row = conn.execute("SELECT * FROM memories WHERE id=?", (memory_id,)).fetchone()
        if row is None:
            raise KeyError(memory_id)
        return dict(row)

    def get_source(self, source_id: str) -> dict:
        with contextlib.closing(self.connection()) as conn:
            row = conn.execute("SELECT * FROM sources WHERE id=?", (source_id,)).fetchone()
        if row is None:
            raise KeyError(source_id)
        return dict(row)

    def list_memories(self, include_inactive: bool = False, as_of=None,
                      topic=None, kind=None) -> list[dict]:
        clauses, args = [], []
        if not include_inactive:
            instant = normalize_time(as_of)
            clauses += ["status='active'", "valid_from<=?", "(valid_until IS NULL OR valid_until>?)"]
            args += [instant, instant]
        elif as_of is not None:
            instant = normalize_time(as_of)
            clauses += ["valid_from<=?", "(valid_until IS NULL OR valid_until>?)"]
            args += [instant, instant]
        if topic is not None:
            topic = _validate_topic(topic)
            # Exact topic or descendants; underscores are literal, not LIKE wildcards.
            clauses += ["(topic=? OR substr(topic,1,?)=?)"]
            args += [topic, len(topic) + 1, topic + "/"]
        if kind is not None:
            if not isinstance(kind, str) or kind not in KINDS:
                raise ValueError("Invalid kind")
            clauses += ["kind=?"]
            args += [kind]
        sql = "SELECT * FROM memories"
        if clauses:
            sql += " WHERE " + " AND ".join(clauses)
        sql += " ORDER BY valid_from DESC, created_at DESC, id"
        with contextlib.closing(self.connection()) as conn:
            return [dict(row) for row in conn.execute(sql, args)]

    def update_memory(self, memory_id: str, changes: dict, expected_version=None) -> dict:
        return self.mutate_memories([
            {"id": memory_id, "changes": changes, "expected_version": expected_version}
        ], event_type="memory_updated")[0]

    def mutate_memories(self, changes: list[dict], event_type: str = "mutation",
                        event_data=None, connection: sqlite3.Connection | None = None) -> list[dict]:
        """Apply a batch atomically; expected versions protect reviewed proposals.

        A supplied connection must already be in a transaction. Its caller owns
        commit/rollback, closing, and export. Empty changes are assertion-only.
        """
        if not isinstance(changes, list) or len(changes) > 10_000:
            raise ValueError("changes must be a list with at most 10000 entries")
        _text(event_type, "event_type", 100)
        if event_data is not None and not isinstance(event_data, dict):
            raise ValueError("event_data must be an object")
        if connection is not None and not connection.in_transaction:
            raise ValueError("Supplied connection must have an active transaction")
        own = connection is None
        conn = connection if connection is not None else self.connection()
        with self._lock:
            try:
                if own:
                    conn.execute("BEGIN IMMEDIATE")
                prepared, seen = [], set()
                for change in changes:
                    if not isinstance(change, dict) or "id" not in change:
                        raise ValueError("Each mutation requires an id and changes object")
                    memory_id = change["id"]
                    if memory_id in seen:
                        raise ValueError("A batch cannot mutate the same memory twice")
                    seen.add(memory_id)
                    raw = conn.execute("SELECT * FROM memories WHERE id=?", (memory_id,)).fetchone()
                    if raw is None:
                        raise KeyError(memory_id)
                    before = dict(raw)
                    expected = change.get("expected_version")
                    if expected is not None:
                        if isinstance(expected, bool) or not isinstance(expected, int):
                            raise ValueError("expected_version must be an integer")
                        if before["version"] != expected:
                            raise VersionConflict(f"Memory {memory_id} changed since review (expected version {expected}, found {before['version']})")
                    patch = change.get("changes")
                    if not isinstance(patch, dict) or not patch.keys() <= MUTABLE_FIELDS:
                        raise ValueError("changes contains unsupported or immutable fields")
                    after = _validate_memory({**before, **patch}) if patch else before.copy()
                    changed = any(after[k] != before[k] for k in patch)
                    if changed:
                        after["version"] = before["version"] + 1
                        after["updated_at"] = utcnow()
                    prepared.append((before, after, changed))
                events = []
                for before, after, changed in prepared:
                    if not changed:
                        continue
                    fields = sorted(MUTABLE_FIELDS) + ["version", "updated_at"]
                    conn.execute(
                        "UPDATE memories SET " + ",".join(f"{key}=?" for key in fields) + " WHERE id=?",
                        [after[key] for key in fields] + [after["id"]],
                    )
                    events.append({"memory_id": after["id"], "before": before, "after": after})
                if events:
                    self._event(conn, event_type, {**(event_data or {}), "changes": events})
                if own:
                    conn.commit()
                result = [after for _, after, _ in prepared]
            except Exception:
                if own:
                    conn.rollback()
                raise
            finally:
                if own:
                    conn.close()
        if own:
            self.refresh_projections()
        return result

    def list_events(self, limit: int = 100) -> list[dict]:
        if isinstance(limit, bool) or not isinstance(limit, int) or not 1 <= limit <= 10_000:
            raise ValueError("limit must be an integer between 1 and 10000")
        with contextlib.closing(self.connection()) as conn:
            rows = conn.execute("SELECT * FROM events ORDER BY id DESC LIMIT ?", (limit,)).fetchall()
        return [{**dict(row), "data": json.loads(row["data"])} for row in rows]

    def get_stats(self) -> dict:
        rows = self.list_memories(include_inactive=True)
        now = utcnow()
        current = [r for r in rows if r["status"] == "active" and r["valid_from"] <= now
                   and (r["valid_until"] is None or r["valid_until"] > now)]
        kinds, topics, statuses = {}, {}, {}
        for row in rows:
            kinds[row["kind"]] = kinds.get(row["kind"], 0) + 1
            topics[row["topic"]] = topics.get(row["topic"], 0) + 1
            statuses[row["status"]] = statuses.get(row["status"], 0) + 1
        with contextlib.closing(self.connection()) as conn:
            source_count = conn.execute("SELECT count(*) FROM sources").fetchone()[0]
            event_count = conn.execute("SELECT count(*) FROM events").fetchone()[0]
        return {"total": len(rows), "active": len(current), "archived": statuses.get("archived", 0),
                "historical": sum(r["status"] == "active" and r["valid_until"] is not None and r["valid_until"] <= now for r in rows),
                "kinds": kinds, "topics": topics, "statuses": statuses,
                "sources": source_count, "events": event_count,
                "projection_errors": list(self.projection_errors)}

    def refresh_projections(self) -> dict:
        """Refresh after a committed write without misreporting durable success.

        Projection failures are recoverable: inspect ``projection_errors`` in
        stats and run an explicit export after repairing disk/path permissions.
        """
        try:
            result = self.export_markdown()
        except Exception as exc:
            self.projection_errors = [f"{type(exc).__name__}: {exc}"]
            logging.getLogger(__name__).warning(
                "Memory is saved, but Markdown projection refresh failed: %s", exc
            )
            return {"error": self.projection_errors[0]}
        self.projection_errors = [
            "Skipped unmanaged projection path: " + path for path in result.get("skipped", [])
        ] + ["Could not write projection " + error for error in result.get("errors", [])]
        return result

    def _safe_path(self, relative: str) -> Path:
        path = self.root / relative
        if path.is_symlink():
            raise ValueError("Refusing to write a symbolic link")
        try:
            path.resolve().relative_to(self.root)
        except ValueError as exc:
            raise ValueError("Managed export path escapes the store") from exc
        return path

    @staticmethod
    def _write_atomic(path: Path, text: str):
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        temporary = path.parent / (".memory-export-" + uuid.uuid4().hex)
        try:
            fd = os.open(str(temporary), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                handle.write(text)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(str(temporary), str(path))
        finally:
            if temporary.exists():
                temporary.unlink()

    @contextlib.contextmanager
    def _export_lock(self):
        # flock coordinates Store objects/processes on macOS/Linux. The RLock
        # also provides serialization on platforms without fcntl.
        lock_path = self._safe_path(".export.lock")
        with self._lock, open(lock_path, "a", encoding="utf-8") as lock:
            try:
                import fcntl
            except ImportError:
                yield
            else:
                fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
                try:
                    yield
                finally:
                    fcntl.flock(lock.fileno(), fcntl.LOCK_UN)

    def export_markdown(self) -> dict:
        """Rebuild owned projections, never deleting or overwriting user files."""
        with self._export_lock():
            with contextlib.closing(self.connection()) as conn:
                conn.execute("BEGIN")
                memories = [dict(r) for r in conn.execute("SELECT * FROM memories ORDER BY topic,valid_from,id")]
                sources = [dict(r) for r in conn.execute("SELECT * FROM sources ORDER BY created_at,id")]
                conn.commit()
            manifest_path = self._safe_path("memory/.manifest.json")
            old_paths = []
            if manifest_path.exists():
                try:
                    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
                    if manifest.get("generator") == "self-evolving-memory-agent":
                        old_paths = manifest.get("paths", [])
                except (ValueError, AttributeError):
                    pass
            paths, skipped, errors = [], [], []
            for row in memories:
                relative = f"memory/{row['topic']}/{row['id']}.md"
                metadata = {k: row[k] for k in row if k != "content"}
                body = (_EXPORT_MARKER + "\n\n# Memory " + row["id"] + "\n\n"
                        + "```json\n" + json.dumps(metadata, indent=2, ensure_ascii=False) + "\n```\n\n"
                        + row["content"] + "\n\n"
                        + f"Evidence: [{row['source_id']}](../../" + "../" * row["topic"].count("/")
                        + f"evidence/{row['source_id']}.json)\n")
                # One refused path (for example a symlinked folder) must not
                # stop every later projection, the index, or the manifest.
                try:
                    path = self._safe_path(relative)
                    if path.exists():
                        existing = path.read_text(encoding="utf-8")
                        if not existing.startswith(_EXPORT_MARKER):
                            skipped.append(relative)
                            continue
                        if existing == body:
                            paths.append(relative)
                            continue
                    self._write_atomic(path, body)
                except (OSError, ValueError) as exc:
                    errors.append(f"{relative}: {exc}")
                    continue
                paths.append(relative)
            for source in sources:
                relative = f"evidence/{source['id']}.json"
                try:
                    path = self._safe_path(relative)
                    # Immutable evidence files are created once, never rewritten.
                    if not path.exists():
                        self._write_atomic(path, json.dumps(source, indent=2, ensure_ascii=False) + "\n")
                except (OSError, ValueError) as exc:
                    errors.append(f"{relative}: {exc}")
            # Compare case-insensitively: on a case-insensitive disk, a topic
            # whose capitalization changed shares one file with its old path.
            current = {relative.casefold() for relative in paths}
            for relative in old_paths:
                if not isinstance(relative, str) or relative.casefold() in current or not relative.startswith("memory/"):
                    continue
                try:
                    path = self._safe_path(relative)
                    if path.is_file() and path.read_text(encoding="utf-8").startswith(_EXPORT_MARKER):
                        path.unlink()
                except (OSError, ValueError) as exc:
                    errors.append(f"{relative}: {exc}")
            index_path = self._safe_path("memory/INDEX.md")
            index = [_EXPORT_MARKER, "", "# Memory index", "", "SQLite and immutable evidence are authoritative. Edit memories through the API or CLI.", ""]
            for row in memories:
                link = f"{row['topic']}/{row['id']}.md"
                label = (row["content"].splitlines() or [""])[0][:100].replace("\\", "/").replace("[", "(").replace("]", ")")
                index.append(f"- [{label}]({link}) — {row['kind']}, {row['status']}, v{row['version']}")
            index_text = "\n".join(index) + "\n"
            existing_index = index_path.read_text(encoding="utf-8") if index_path.exists() else None
            if existing_index is None or (existing_index.startswith(_EXPORT_MARKER) and existing_index != index_text):
                self._write_atomic(index_path, index_text)
            elif not existing_index.startswith(_EXPORT_MARKER):
                skipped.append("memory/INDEX.md")
            manifest_text = json.dumps({"generator": "self-evolving-memory-agent", "paths": paths}, indent=2) + "\n"
            if not manifest_path.exists() or manifest_path.read_text(encoding="utf-8") != manifest_text:
                self._write_atomic(manifest_path, manifest_text)
            return {"memories": len(paths), "sources": len(sources), "skipped": skipped, "errors": errors}
